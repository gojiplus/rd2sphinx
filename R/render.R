#' Render an R package's reference documentation for Sphinx
#'
#' Parse the package's generated `man/*.Rd` files and write semantic
#' reStructuredText pages understood by the bundled Sphinx R domain.
#'
#' @param path Path to an R package source directory.
#' @param docs_dir Sphinx source directory, relative to `path` by default.
#' @param reference_dir Directory below `docs_dir` for generated reference pages.
#' @param include Either `"exports"` to document exported objects plus package and
#'   data topics, or `"all"` to document every Rd topic.
#' @param clean Remove previously generated reference pages before rendering.
#' @param quiet Suppress the summary message.
#' @return Invisibly, a character vector of generated files.
#' @export
render_sphinx <- function(
    path = ".",
    docs_dir = "docs",
    reference_dir = "reference",
    include = c("exports", "all"),
    clean = TRUE,
    quiet = FALSE) {
  include <- match.arg(include)
  path <- normalizePath(path, winslash = "/", mustWork = TRUE)
  description <- read_package_description(path)
  package <- description$Package
  docs_path <- rd2sphinx_path(docs_dir, path)
  reference_path <- file.path(docs_path, reference_dir)
  man_path <- file.path(path, "man")

  if (!dir.exists(man_path)) {
    stop("No man/ directory found. Run roxygen2 before render_sphinx().", call. = FALSE)
  }

  ensure_dir(reference_path)
  install_sphinx_extension(docs_path)

  rd_db <- tools::Rd_db(dir = path, stages = "build")
  if (!length(rd_db)) {
    stop("No Rd topics found under ", man_path, call. = FALSE)
  }

  rd_names <- names(rd_db)
  if (is.null(rd_names)) {
    rd_names <- rep("", length(rd_db))
  }
  topics <- Map(read_rd_topic, rd = unname(rd_db), file = rd_names)
  exports <- read_namespace_exports(path)
  keep <- vapply(topics, should_include_topic, logical(1L), exports = exports, include = include)
  topics <- topics[keep]
  alias_map <- build_alias_map(topics, package)

  if (isTRUE(clean)) {
    clean_generated_reference(reference_path)
  }

  generated <- character()
  entries <- list()
  used_slugs <- character()

  for (topic in topics) {
    slug <- unique_slug(slugify(topic$canonical), used_slugs)
    used_slugs <- c(used_slugs, slug)
    output <- file.path(reference_path, paste0(slug, ".rst"))
    write_utf8(render_topic_rst(topic, package = package, aliases = alias_map), output)
    generated <- c(generated, output)
    entries[[length(entries) + 1L]] <- list(
      title = topic$title,
      canonical = topic$canonical,
      kind = topic$kind,
      slug = slug
    )
  }

  index <- render_reference_index(package, entries)
  index_path <- file.path(reference_path, "index.rst")
  write_utf8(index, index_path)
  generated <- c(index_path, generated)

  if (!isTRUE(quiet)) {
    message(
      "Generated ", length(entries), " reference page",
      if (length(entries) == 1L) "" else "s",
      " for ", package, " in ", reference_path
    )
  }

  invisible(generated)
}

install_sphinx_extension <- function(docs_path) {
  extension <- system.file("sphinx", "rd2sphinx_domain.py", package = "rd2sphinx")
  if (!nzchar(extension) || !file.exists(extension)) {
    stop("Bundled Sphinx extension is missing from the rd2sphinx installation.", call. = FALSE)
  }
  target <- file.path(docs_path, "_ext", "rd2sphinx_domain.py")
  ensure_dir(dirname(target))
  if (!file.copy(extension, target, overwrite = TRUE)) {
    stop("Could not copy the Sphinx extension to ", target, call. = FALSE)
  }
  invisible(target)
}

clean_generated_reference <- function(reference_path) {
  files <- list.files(reference_path, pattern = "\\.rst$", full.names = TRUE)
  for (file in files) {
    first <- readLines(file, n = 1L, warn = FALSE, encoding = "UTF-8")
    if (length(first) && identical(first, ".. Generated by rd2sphinx; do not edit.")) {
      unlink(file)
    }
  }
  invisible(reference_path)
}

unique_slug <- function(slug, used) {
  if (!slug %in% used) {
    return(slug)
  }
  i <- 2L
  candidate <- paste0(slug, "-", i)
  while (candidate %in% used) {
    i <- i + 1L
    candidate <- paste0(slug, "-", i)
  }
  candidate
}

render_reference_index <- function(package, entries) {
  lines <- c(
    ".. Generated by rd2sphinx; do not edit.",
    "",
    rst_heading(paste(package, "reference"), "="),
    "",
    "The pages in this section are generated from the package's Rd help topics.",
    "",
    ".. toctree::",
    "   :maxdepth: 1",
    "   :hidden:",
    ""
  )

  if (length(entries)) {
    lines <- c(lines, paste0("   ", vapply(entries, `[[`, character(1L), "slug")))
  }

  groups <- c(
    "function" = "Functions",
    "data" = "Data",
    "class" = "Classes",
    "package" = "Package",
    "topic" = "Other topics"
  )
  for (kind in names(groups)) {
    group <- Filter(function(entry) identical(entry$kind, kind), entries)
    if (!length(group)) next

    lines <- c(lines, "", rst_heading(groups[[kind]], "-"), "")
    for (entry in group) {
      role <- switch(
        kind,
        "function" = "func",
        data = "data",
        class = "class",
        package = "pkg",
        "topic"
      )
      lines <- c(lines, paste0("* :r:", role, ":`", entry$canonical, "` \u2014 ", rst_text(entry$title)))
    }
  }

  c(lines, "")
}
